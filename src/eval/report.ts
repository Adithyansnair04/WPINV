import type { computeMetrics, EvalCase } from './metrics.js';

type Metrics = ReturnType<typeof computeMetrics>;
interface RunFile {
  model: string;
  status: 'ok' | 'not_run';
  reason?: string;
  timestamp: string;
  caseCount?: number;
  casesScored?: number;
  blocked?: string[];
  partial?: boolean;
  metrics?: Metrics;
}

const pct = (r: { num: number; den: number; pct: number | null }) => (r.pct === null ? 'n/a' : `${r.pct}% (${r.num}/${r.den})`);

export function renderSummary(runs: RunFile[], cases: EvalCase[], set: 'main' | 'holdout' = 'main'): string {
  const ok = runs.filter((r) => r.status === 'ok' && r.metrics).sort((a, b) => a.model.localeCompare(b.model));
  const notRun = runs.filter((r) => r.status === 'not_run');
  const col = (f: (m: Metrics) => string) => ok.map((r) => f(r.metrics!)).join(' | ');
  const rows: [string, (m: Metrics) => string][] = [
    ['Action accuracy (create/clarify/respond/ignore)', (m) => pct(m.headline.action_accuracy)],
    ['Customer match accuracy', (m) => pct(m.headline.customer_match_accuracy)],
    ['Item match accuracy', (m) => pct(m.headline.item_match_accuracy)],
    ['Quantity accuracy (extraction)', (m) => pct(m.headline.quantity_accuracy)],
    ['Rate accuracy (extraction)', (m) => pct(m.headline.rate_accuracy)],
    ['Intent accuracy (extraction)', (m) => pct(m.extraction.intent_accuracy)],
    ['Line-count accuracy (extraction)', (m) => pct(m.extraction.line_count_accuracy)],
    ['Clarification recall', (m) => pct(m.headline.clarification_recall)],
    ['Unnecessary clarification rate', (m) => pct(m.headline.unnecessary_clarification_rate)],
    ['Exactly-correct invoices (of expected creates)', (m) => pct(m.headline.exact_invoice_rate)],
    ['**Confidently wrong invoices**', (m) => `${m.headline.confidently_wrong_invoices}${m.confidently_wrong_case_ids.length ? ` (${m.confidently_wrong_case_ids.join(', ')})` : ''}`],
    ['Non-invoice false positives', (m) => pct(m.headline.non_invoice_false_positives)],
    ['Latency mean / p50 / p95 / max (ms per model turn)', (m) => `${m.latency_ms.mean} / ${m.latency_ms.p50} / ${m.latency_ms.p95} / ${m.latency_ms.max}`],
    ['Model failures / invalid outputs / HTTP retries / 429s', (m) => `${m.reliability.model_failures} / ${m.reliability.invalid_outputs} / ${m.reliability.http_retries} / ${m.reliability.rate_limit_events}`],
  ];
  const categories = [...new Set(cases.map((c) => c.category))];
  return [
    set === 'holdout' ? '# Held-out evaluation results' : '# Evaluation results',
    '',
    'Generated by `npm run eval`. Zoho is mocked from `data/seed`; no chat or real invoices are involved. Numbers below are measured, not estimated. Cases blocked by provider quota are excluded from that model’s metrics and shown under "Cases scored"; compare models on equal coverage.',
    '',
    ok.length ? `| Metric | ${ok.map((r) => `\`${r.model}\``).join(' | ')} |` : '_No model has been run yet._',
    ok.length ? `|---|${ok.map(() => '---').join('|')}|` : '',
    ...(ok.length ? rows.map(([label, f]) => `| ${label} | ${col(f)} |`) : []),
    ok.length ? `| Cases scored (rest blocked by quota) | ${ok.map((r) => `${r.casesScored ?? r.caseCount ?? '?'}/${r.caseCount ?? '?'}`).join(' | ')} |` : '',
    ok.length ? `| Run at (UTC) | ${ok.map((r) => `${r.timestamp.slice(0, 16).replace('T', ' ')}${r.partial ? ' (partial)' : ''}`).join(' | ')} |` : '',
    '',
    ...(ok.length
      ? [
          '## Action accuracy by category',
          '',
          `| Category | ${ok.map((r) => `\`${r.model}\``).join(' | ')} |`,
          `|---|${ok.map(() => '---').join('|')}|`,
          ...categories.map((cat) => `| ${cat} | ${ok.map((r) => { const v = r.metrics!.per_category[cat]; return v ? `${v.ok}/${v.n}` : '-'; }).join(' | ')} |`),
          '',
        ]
      : []),
    ...(notRun.length ? ['## Not run', '', ...notRun.map((r) => `- \`${r.model}\`: ${r.reason}`), ''] : []),
  ].join('\n');
}
